#!/bin/bash
# generate-handoff.sh — Zero-AI handoff generator
# Creates a handoff.md from git state + interactive prompts when all AI tools
# are out of tokens. Run from any git repo.
#
# Usage: ./generate-handoff.sh [project-path]

set -euo pipefail

# --- Helpers ---

bold() { printf '\033[1m%s\033[0m' "$1"; }
dim() { printf '\033[2m%s\033[0m' "$1"; }

prompt() {
    local label="$1" default="${2:-}"
    printf '\n%s' "$(bold "$label")"
    if [ -n "$default" ]; then
        printf ' %s' "$(dim "(default: $default)")"
    fi
    printf ': '
    read -r answer
    if [ -z "$answer" ] && [ -n "$default" ]; then
        answer="$default"
    fi
    echo "$answer"
}

prompt_optional() {
    local label="$1"
    printf '\n%s %s: ' "$(bold "$label")" "$(dim "(press Enter to skip)")"
    read -r answer
    echo "$answer"
}

# --- Navigate to project ---

PROJECT_DIR="${1:-.}"
cd "$PROJECT_DIR" || { echo "Error: cannot cd to $PROJECT_DIR"; exit 1; }

if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "Error: $(pwd) is not a git repository."
    exit 1
fi

PROJECT_ROOT="$(git rev-parse --show-toplevel)"
cd "$PROJECT_ROOT"

echo ""
echo "$(bold 'Handoff Kit — Zero-AI Generator')"
echo "================================="
echo "Project: $PROJECT_ROOT"
echo ""

# --- Read git state ---

GIT_HEAD="$(git rev-parse --short HEAD 2>/dev/null || echo 'no-commits')"
GIT_BRANCH="$(git branch --show-current 2>/dev/null || echo 'detached')"
TIMESTAMP="$(date -u +%Y-%m-%dT%H:%M:%S%z 2>/dev/null || date +%Y-%m-%dT%H:%M:%S)"
GIT_LOG="$(git log --oneline -10 2>/dev/null || echo '(no commits)')"
GIT_REMOTES="$(git remote -v 2>/dev/null || echo '(no remotes)')"

# Changed files: staged + unstaged + untracked
STAGED="$(git diff --cached --name-status 2>/dev/null || true)"
UNSTAGED="$(git diff --name-status 2>/dev/null || true)"
UNTRACKED="$(git ls-files --others --exclude-standard 2>/dev/null || true)"

# Detect source tool from environment
if [ -n "${CLAUDE_CODE_USE_VERTEX:-}" ] || [ -d "$HOME/.claude" ]; then
    SOURCE_GUESS="claude-code"
elif [ -n "${CODEX_HOME:-}" ] || [ -d "$HOME/.codex" ]; then
    SOURCE_GUESS="codex"
elif [ -d "$HOME/.cursor" ]; then
    SOURCE_GUESS="cursor"
else
    SOURCE_GUESS="manual"
fi

# --- Interactive prompts ---

echo "$(dim 'Fill in what you can — you can edit everything in your editor afterward.')"

TASK="$(prompt 'What is the task? (one sentence)')"
NEXT_STEP="$(prompt 'What should be done next?')"
GOTCHAS="$(prompt_optional 'Any gotchas or blockers?')"
SOURCE="$(prompt 'Source tool' "$SOURCE_GUESS")"

# --- Build changed files section ---

build_changed_files() {
    local output=""
    if [ -n "$STAGED" ]; then
        output+="### Staged
$STAGED

"
    fi
    if [ -n "$UNSTAGED" ]; then
        output+="### Unstaged
$UNSTAGED

"
    fi
    if [ -n "$UNTRACKED" ]; then
        output+="### Untracked
$UNTRACKED

"
    fi
    if [ -z "$output" ]; then
        output="(no changes detected)"
    fi
    echo "$output"
}

CHANGED_FILES="$(build_changed_files)"

# --- Build plan from recent commits ---

build_plan_from_git() {
    local i=1
    while IFS= read -r line; do
        if [ -n "$line" ]; then
            echo "$i. $line"
            echo "   - Files: (check git show for this commit)"
            echo "   - Verify: \`(fill in)\`"
            echo "   - Status: done"
            i=$((i + 1))
        fi
    done <<< "$GIT_LOG"
    echo "$i. (next step — fill in)"
    echo "   - Files: "
    echo "   - Verify: \`(fill in)\`"
    echo "   - Status: not started"
}

PLAN_STEPS="$(build_plan_from_git)"

# --- Generate handoff.md ---

OUTPUT="$PROJECT_ROOT/handoff.md"

cat > "$OUTPUT" << HANDOFF_CONTENT
<!-- Generated: $TIMESTAMP -->
<!-- Git HEAD: $GIT_HEAD -->
<!-- Source: $SOURCE -->
# Handoff — $TASK

## Original Task
$TASK

<!-- DURABLE — valid even when progress is outdated -->

## Architecture
<!-- TODO: Describe the system design, key components, tech stack -->

## Repo and Access
- Branch: \`$GIT_BRANCH\`
- Remotes:
\`\`\`
$GIT_REMOTES
\`\`\`

## Gotchas
${GOTCHAS:--- TODO: Add any hard-won lessons, constraints, or failed approaches}

## Key Files
<!-- TODO: List important files and their purpose -->

<!-- VOLATILE — must match current git state to be trusted -->

## Plan

Goal: $TASK

### Steps
$PLAN_STEPS

### Edge cases / risks
<!-- TODO: Fill in if known -->

### Final verification
- \`(fill in the command to verify everything works)\`

## Files Changed
$CHANGED_FILES

## Current State
<!-- TODO: What works, what doesn't -->

## Blockers
${GOTCHAS:-(none noted)}

## Next Steps
$NEXT_STEP

## Context
<!-- TODO: Decisions, constraints, or context the next session needs -->

---
*Generated by generate-handoff.sh (zero-AI fallback) — review and fill in TODO sections before handing off.*
HANDOFF_CONTENT

echo ""
echo "$(bold 'Generated:') $OUTPUT"
echo ""

# --- Open in editor ---

EDITOR="${EDITOR:-${VISUAL:-vi}}"
echo "Opening in $(bold "$EDITOR") for review..."
echo "$(dim 'Fill in the TODO sections, save, and close when done.')"
echo ""

"$EDITOR" "$OUTPUT"

echo ""
echo "$(bold 'Done.') handoff.md saved at: $OUTPUT"
echo ""
echo "To deliver:"
echo "  SSH:  scp $OUTPUT user@host:~/project/handoff.md"
echo "  Git:  git add handoff.md && git commit -m '[handoff]' && git push"
echo "  Paste: cat $OUTPUT | pbcopy  (macOS)"
echo ""
